"""Export the dense CD8 display sample from the saved FlowCV and Slingshot outputs.

Run from this repo with: python3 tools/export_cd8_map.py /path/to/flowcv
"""

import argparse
import gzip
import json
from pathlib import Path

import numpy as np

THESIS_CLUSTERS = [14, 13, 12, 21, 10, 11, 15, 17, 18, 19]
PRIORITY_CLUSTERS = [14, 13, 15, 17]  # Naive, central memory, both resident memory phenotypes
DISPLAY_COUNT = 32_000
RUN = "03af8504-0756-4810-9770-5d89c8c9d5c3"


def export(flowcv_root, output):
    run = flowcv_root / "backend/app/data/run_artifacts" / RUN
    analysis = flowcv_root / "output/rcc-reanalysis-2026-11-10"
    pseudotime = analysis / "pseudotime"
    embedding = next(run.glob("embedding-cd8_embedding_payload_*.json.gz"))
    labels = next(run.glob("flowsom_review-cd8_clustering_labels_*.npz"))
    with gzip.open(embedding, "rt") as file:
        points = json.load(file)["points"]
    assert all(point["event_idx"] == i for i, point in enumerate(points))

    xy = np.array([(point["x"], point["y"]) for point in points])
    sources = np.array([point["source_file"] for point in points])
    lab = np.load(labels)["labels"]
    match = json.loads((analysis / "thesis-match/match.json").read_text())["CD8"]
    cluster_for_label = {row["mc"]: row["best"] for row in match}
    clusters = np.array([cluster_for_label[int(label)] for label in lab])
    xyz = np.load(pseudotime / "umap/cd8_umap3d.npy").astype(float)
    assert len(xy) == len(lab) == len(xyz) == 68_936

    xyz -= np.median(xyz, axis=0)
    xyz /= np.percentile(np.abs(xyz), 99, axis=0).max()
    weights = np.fromfile(pseudotime / "out_weights.f8", dtype="<f8").reshape(len(xy), 4)
    dominant = np.argmax(np.nan_to_num(weights, nan=0), axis=1)

    # Keep the original 1,000 cells from each FCS, then add all four priority
    # populations and sample the remaining events without replacement.
    rng = np.random.default_rng(7)
    original = np.concatenate([
        rng.choice(np.flatnonzero(sources == file), 1_000, replace=False)
        for file in sorted(set(sources))
    ])
    priority = np.flatnonzero(np.isin(clusters, PRIORITY_CLUSTERS))
    keep = np.union1d(original, priority)
    remaining = np.setdiff1d(np.arange(len(xy)), keep)
    keep = np.concatenate([keep, rng.choice(remaining, DISPLAY_COUNT - len(keep), replace=False)])
    rng.shuffle(keep)
    assert len(np.unique(keep)) == DISPLAY_COUNT

    # Multiply coordinates by 1,000 for a compact JS payload with fixed precision.
    cell_types = {cluster: i for i, cluster in enumerate(THESIS_CLUSTERS)}
    lo, hi = np.percentile(xy, [0.5, 99.5], axis=0)
    data = {
        "ct": [cell_types[int(cluster)] for cluster in clusters[keep]],
        "dom": dominant[keep].tolist(),
        "xy": np.rint(xy[keep] * 1000).astype(int).ravel().tolist(),
        "p3": np.rint(xyz[keep] * 1000).astype(int).ravel().tolist(),
        "xr": [round(float(lo[0]), 2), round(float(hi[0]), 2)],
        "yr": [round(float(lo[1]), 2), round(float(hi[1]), 2)],
        "n_cd8": len(xy),
    }
    output.write_text(
        "// Generated by tools/export_cd8_map.py. Coordinates are stored in thousandths.\n"
        "window.DECK_RCC_UMAP_DETAIL = " + json.dumps(data, separators=(",", ":")) + ";\n"
    )
    print(f"{len(keep):,} unique cells across {len(set(sources[keep]))} files")
    for cluster in PRIORITY_CLUSTERS:
        selected = np.count_nonzero(clusters[keep] == cluster)
        available = np.count_nonzero(clusters == cluster)
        assert selected == available
        print(f"Thesis cluster {cluster}: {selected:,}/{available:,}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("flowcv_root", type=Path)
    parser.add_argument("--output", type=Path, default=Path("data/rcc-cd8-umap-detail.js"))
    args = parser.parse_args()
    export(args.flowcv_root, args.output)
