"""Per-cell data for the interactive CD8 map (slide 17), for exactly the same 32,000 cells as the title slide
(data/rcc-cd8-umap-detail.js): marker expression, tissue, dominant Slingshot lineage and pseudotime.

Run from this repo with: python3 tools/export_cd8_explorer.py /path/to/flowcv
The selection replicates tools/export_cd8_map.py and is checked against data/rcc-cd8-umap-detail.js.
"""

import argparse
import base64
import gzip
import json
import re
import sys
from pathlib import Path

import numpy as np

THESIS_CLUSTERS = [14, 13, 12, 21, 10, 11, 15, 17, 18, 19]
PRIORITY_CLUSTERS = [14, 13, 15, 17]
DISPLAY_COUNT = 32_000
RUN = "03af8504-0756-4810-9770-5d89c8c9d5c3"
# Display order: lineage, memory, residence, exhaustion, cytotoxicity, regulation, proliferation.
MARKERS = ["CD8", "CD4", "CCR7", "TCF-1", "CD45RO", "CD69", "CD103", "PD-1", "TIM-3", "CD39", "GZMB", "GNLY",
           "CX3CR1", "CD25", "FOXP3", "CCR6", "Ki67"]


def b64(values):
    return base64.b64encode(np.asarray(values, dtype=np.uint8).tobytes()).decode()


def export(flowcv_root, output, detail):
    run = flowcv_root / "backend/app/data/run_artifacts" / RUN
    analysis = flowcv_root / "output/rcc-reanalysis-2026-11-10"
    pseudotime = analysis / "pseudotime"
    sys.path.insert(0, str(analysis))
    from reanalysis_common import FEATURES36, SEL

    with gzip.open(next(run.glob("embedding-cd8_embedding_payload_*.json.gz")), "rt") as file:
        points = json.load(file)["points"]
    xy = np.array([(p["x"], p["y"]) for p in points])
    sources = np.array([p["source_file"] for p in points])
    lab = np.load(next(run.glob("flowsom_review-cd8_clustering_labels_*.npz")))["labels"]
    match = json.loads((analysis / "thesis-match/match.json").read_text())["CD8"]
    cluster_for_label = {row["mc"]: row["best"] for row in match}
    clusters = np.array([cluster_for_label[int(label)] for label in lab])
    n = len(xy)
    lines = (pseudotime / "out_lineages.txt").read_text().split("\n")
    lineages = len([line for line in lines if line.strip()])
    weights = np.fromfile(pseudotime / "out_weights.f8", dtype="<f8").reshape(n, lineages)
    pt = np.fromfile(pseudotime / "out_pseudotime.f8", dtype="<f8").reshape(n, lineages)
    dominant = np.argmax(np.nan_to_num(weights, nan=0), axis=1)

    # Same display sample as tools/export_cd8_map.py (same generator, seed and call order).
    rng = np.random.default_rng(7)
    original = np.concatenate([rng.choice(np.flatnonzero(sources == f), 1_000, replace=False) for f in sorted(set(sources))])
    keep = np.union1d(original, np.flatnonzero(np.isin(clusters, PRIORITY_CLUSTERS)))
    remaining = np.setdiff1d(np.arange(n), keep)
    keep = np.concatenate([keep, rng.choice(remaining, DISPLAY_COUNT - len(keep), replace=False)])
    rng.shuffle(keep)

    text = detail.read_text()
    reference = json.loads(text[text.index("{"):text.rstrip().rstrip(";").rindex("}") + 1])
    cell_types = {cluster: i for i, cluster in enumerate(THESIS_CLUSTERS)}
    assert reference["ct"] == [cell_types[int(c)] for c in clusters[keep]], "cell types differ from the title-slide sample"
    assert reference["dom"] == dominant[keep].tolist(), "lineages differ from the title-slide sample"

    # Marker expression (MNN-corrected arcsinh, as in the analysis): 1st–99th percentile of all CD8 cells -> 0..255.
    matrix = np.load(run / "flowsom_review-cd8_analysis_input.npz")["matrix"]
    expression = []
    for marker in MARKERS:
        values = matrix[:, FEATURES36.index("MNN-" + marker)]
        lo, hi = np.percentile(values, [1, 99])
        expression.append(np.clip(np.rint((values[keep] - lo) / (hi - lo) * 255), 0, 255))

    # Pseudotime along each cell's dominant lineage, scaled by that lineage's 99.5% weighted quantile (as the trajectory slides).
    def weighted_quantile(v, w, q):
        o = np.argsort(v); c = np.cumsum(w[o]); return float(v[o][min(np.searchsorted(c, q * c[-1]), len(v) - 1)])
    ends = []
    for j in range(lineages):
        ok = np.isfinite(pt[:, j]) & (weights[:, j] > 0)
        ends.append(weighted_quantile(pt[ok, j], weights[ok, j], 0.995))
    own = pt[keep, dominant[keep]] / np.array(ends)[dominant[keep]]
    tumor = np.array([re.match(r"norm_\d+ ([ST])_", f).group(1) == "T" for f in sources[keep]])

    data = {
        "n": DISPLAY_COUNT,
        "markers": MARKERS,
        "expr": b64(np.stack(expression, axis=1)),  # cell-major: cell i, marker j at i * len(MARKERS) + j
        "t": b64(np.where(np.isfinite(own), np.clip(np.rint(own * 254), 0, 254), 255)),  # 255 = no pseudotime
        "tumor": b64(tumor.astype(np.uint8)),
        "source": f"FlowCV run {RUN[:8]} (CD8 FlowSOM Review input, MNN-corrected) · Slingshot rerun of 10 Nov 2026",
    }
    output.write_text(
        "// Generated by tools/export_cd8_explorer.py — same cells as data/rcc-cd8-umap-detail.js; byte arrays are base64.\n"
        "window.DECK_RCC_EXPLORER = " + json.dumps(data, separators=(",", ":")) + ";\n"
    )
    print(f"{DISPLAY_COUNT:,} cells · {len(MARKERS)} markers · tumor {tumor.mean():.1%} · {output.stat().st_size / 1e6:.2f} MB")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("flowcv_root", type=Path)
    parser.add_argument("--output", type=Path, default=Path("data/rcc-cd8-explorer.js"))
    parser.add_argument("--detail", type=Path, default=Path("data/rcc-cd8-umap-detail.js"))
    args = parser.parse_args()
    export(args.flowcv_root, args.output, args.detail)
